function weekdayOf(iso: string): Day {
  return dayFromIso(iso) ?? "Lunes";
}

function crew(
  routeId: string,
  vehicleId: string,
  technicianIds: string[],
  mode: Mode,
): Assignment[] {
  return technicianIds.map((technicianId) => ({
    id: `a-${routeId}-${technicianId}`,
    routeId,
    technicianId,
    vehicleId,
    mode,
    peopleInVan: Math.min(technicianIds.length, 2),
    peopleOnRoute: technicianIds.length,
    perDiem: 10000,
  }));
}

